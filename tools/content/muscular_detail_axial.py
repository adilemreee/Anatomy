"""Individual muscles of the head, neck, back, thorax and pelvic floor.

The group entries (muscular_trunk.py: "Kanat kasları", "Göz dışı kasları"…)
give the overview; these entries give each muscle on its own, so it can be
picked in 3D, read, asked and studied as a card. `D(parent, ...)` takes its
group and region from the group entry.
"""
from muscular_trunk import M

PARENTS = {}


def D(parent, id, tr, la, en, summary, origin, insertion, nerve, blood, action, models, clinical=(), tus=(), related=(), aliases=()):
    PARENTS[id] = parent
    return dict(parent=parent, args=(id, tr, la, en), summary=summary, origin=origin, insertion=insertion, nerve=nerve,
                blood=blood, action=action, models=models, clinical=clinical, tus=tus, related=related, aliases=aliases)


# muscles without a group entry: their group and region
LOOSE = {"@neck": ("Boyun kasları", "neck")}


def build(specs, parents):
    """Entries from specs; `parents` maps a group entry id to its (group, region)."""
    out = []
    for s in specs:
        loose = s["parent"].startswith("@")
        group, region = LOOSE[s["parent"]] if loose else parents[s["parent"]]
        id_, tr, la, en = s["args"]
        related = ([] if loose else [s["parent"]]) + list(s["related"])
        out.append(M(id_, tr, la, en, group, region, s["summary"], s["origin"], s["insertion"], s["nerve"], s["blood"],
                     s["action"], clinical=s["clinical"], related=related, models=s["models"],
                     aliases=s["aliases"], tus=s["tus"]))
        if not loose:
            out[-1]["parent"] = s["parent"]
    return out


